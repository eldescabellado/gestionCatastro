-- Este script crea las tablas de Estados y Municipios de Venezuela
-- Adaptado de MySQL a PostgreSQL

-- Tabla de Estados de Venezuela
CREATE TABLE IF NOT EXISTS Estados (
    EstadoID        SERIAL PRIMARY KEY,
    Nombre          VARCHAR(100) NOT NULL UNIQUE,
    CodigoISO       VARCHAR(10),
    Activo          BOOLEAN DEFAULT TRUE
);

-- Tabla de Municipios de Venezuela
CREATE TABLE IF NOT EXISTS Municipios (
    MunicipioID     SERIAL PRIMARY KEY,
    EstadoID        INTEGER NOT NULL REFERENCES Estados(EstadoID),
    Nombre          VARCHAR(200) NOT NULL,
    EsCapital       BOOLEAN DEFAULT FALSE,
    Activo          BOOLEAN DEFAULT TRUE
);

-- Índices
CREATE INDEX IF NOT EXISTS idx_municipios_estado ON Municipios(EstadoID);
CREATE INDEX IF NOT EXISTS idx_municipios_nombre ON Municipios(Nombre);

