-- Vista de Municipios con Estado
CREATE OR REPLACE VIEW vw_municipios_estado AS
SELECT
    m.MunicipioID,
    m.Nombre AS Municipio,
    e.Nombre AS Estado,
    m.EsCapital
FROM Municipios m
INNER JOIN Estados e ON m.EstadoID = e.EstadoID
WHERE m.Activo = TRUE AND e.Activo = TRUE
ORDER BY e.Nombre, m.Nombre;

